#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_builtin_theme_id_resolves() {
        let themes = builtin_themes();
        assert!(themes.len() > 800, "the theme collection is bundled");
        for theme in themes {
            assert_eq!(builtin_theme(theme.id), Some(theme.colors), "{}", theme.id);
            assert_eq!(normalize_theme_id(theme.id), theme.id);
        }
        assert!(builtin_theme("no-such-theme").is_none());
    }

    #[test]
    fn earlier_builtin_theme_ids_still_resolve() {
        for id in [
            "tokyo-night",
            "catppuccin-mocha",
            "dracula",
            "gruvbox-dark",
            "nord",
            "solarized-dark",
            "one-dark",
            "monokai",
            "material-dark",
            "palenight",
            "tomorrow-night",
            "oceanic-next",
        ] {
            assert!(builtin_theme(id).is_some(), "{id}");
        }
        assert_eq!(builtin_theme("tokyo-night"), Some(tokyo_night()));
    }

    #[test]
    fn builtin_theme_names_normalize_to_their_ids() {
        // Config values are normalized when parsed, so `theme = "<name>"`
        // must land on the theme with that name.
        for theme in builtin_themes() {
            assert_eq!(normalize_theme_id(theme.name), theme.id, "{}", theme.name);
        }
    }

    #[test]
    fn builtin_theme_ids_are_unique() {
        let mut ids: Vec<_> = builtin_themes().iter().map(|theme| theme.id).collect();
        ids.sort_unstable();
        let count = ids.len();
        ids.dedup();
        assert_eq!(ids.len(), count);
    }

    #[test]
    fn collection_themes_resolve_by_name_or_id() {
        let dracula = find_builtin_theme("Dracula").expect("Dracula");
        assert_eq!(dracula.id, "dracula");
        assert_eq!(dracula.colors.background, Rgb8::new(0x28, 0x2a, 0x36));
        assert_eq!(dracula.colors.ansi[1], Rgb8::new(0xff, 0x55, 0x55));
        assert_eq!(
            find_builtin_theme("dracula-plus").map(|theme| theme.name),
            Some("Dracula+")
        );
        assert!(find_builtin_theme("Catppuccin Mocha").is_some());
    }

    #[test]
    fn termy_light_is_an_offline_builtin_with_a_light_background() {
        let colors = builtin_theme("termy-light").expect("termy-light builtin");

        assert_eq!(colors.foreground, Rgb8::new(0x09, 0x09, 0x0B));
        assert_eq!(colors.background, Rgb8::new(0xFA, 0xFA, 0xF9));
        assert_eq!(colors.cursor, Rgb8::new(0x4F, 0xA8, 0x4A));
    }
}
