/// A theme every Termy host ships offline: core config, libtermy, the CLI
/// and the desktop app.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct BuiltinTheme {
    /// The normalized id config files use, such as `catppuccin-mocha`.
    pub id: &'static str,
    /// The display name, such as `Catppuccin Mocha`.
    pub name: &'static str,
    pub colors: ThemeColors,
}

/// The theme collection from iTerm2-Color-Schemes (MIT; see
/// `collection/LICENSE`), generated by `scripts/import-themes.py`. One theme
/// per line: id, name, background, foreground, cursor, 16 ANSI colors.
const COLLECTION_THEMES: &str = include_str!("collection/themes.tsv");

/// Termy's own themes, which [`builtin_themes`] lists first.
pub const TERMY_THEME_IDS: [&str; 2] = ["termy", "termy-light"];

/// Termy's own themes first ([`TERMY_THEME_IDS`]), then the collection in
/// name order. The other palettes
/// below are bundled only for embedders that list them themselves (the web
/// package).
pub fn builtin_themes() -> &'static [BuiltinTheme] {
    static THEMES: OnceLock<Vec<BuiltinTheme>> = OnceLock::new();
    THEMES.get_or_init(|| {
        let mut themes = vec![
            BuiltinTheme {
                id: "termy",
                name: "Termy",
                colors: termy(),
            },
            BuiltinTheme {
                id: "termy-light",
                name: "Termy Light",
                colors: termy_light(),
            },
        ];
        let mut collection: Vec<BuiltinTheme> = COLLECTION_THEMES
            .lines()
            .filter_map(parse_collection_theme)
            .chain(
                LEGACY_THEMES
                    .iter()
                    .map(|&(id, name, colors)| BuiltinTheme {
                        id,
                        name,
                        colors: colors(),
                    }),
            )
            .collect();
        collection.sort_by_cached_key(|theme| theme.name.to_ascii_lowercase());
        themes.extend(collection);
        themes
    })
}

/// Termy's earlier built-in themes whose ids the collection does not use.
/// They keep existing configs looking exactly as before.
type LegacyTheme = (&'static str, &'static str, fn() -> ThemeColors);

const LEGACY_THEMES: &[LegacyTheme] = &[
    ("tokyo-night", "Tokyo Night", tokyo_night),
    ("solarized-dark", "Solarized Dark", solarized_dark),
    ("one-dark", "One Dark", one_dark),
    ("monokai", "Monokai", monokai),
    ("palenight", "Palenight", palenight),
];

fn parse_collection_theme(line: &'static str) -> Option<BuiltinTheme> {
    let mut fields = line.split('\t');
    let id = fields.next()?;
    let name = fields.next()?;
    let mut colors = fields.map(Rgb8::from_hex);
    let background = colors.next()??;
    let foreground = colors.next()??;
    let cursor = colors.next()??;
    let mut ansi = [Rgb8::new(0, 0, 0); 16];
    for slot in &mut ansi {
        *slot = colors.next()??;
    }
    Some(BuiltinTheme {
        id,
        name,
        colors: ThemeColors {
            ansi,
            foreground,
            background,
            cursor,
        },
    })
}

/// The built-in theme with this id, in any spelling [`normalize_theme_id`]
/// accepts; `termylight` is accepted for `termy-light`.
pub fn find_builtin_theme(theme_id: &str) -> Option<&'static BuiltinTheme> {
    let id = match normalize_theme_id(theme_id).as_str() {
        "termylight" => "termy-light".to_string(),
        id => id.to_string(),
    };
    builtin_themes().iter().find(|theme| theme.id == id)
}

/// Colors of a built-in theme. See [`find_builtin_theme`].
pub fn builtin_theme(theme_id: &str) -> Option<ThemeColors> {
    find_builtin_theme(theme_id).map(|theme| theme.colors)
}

